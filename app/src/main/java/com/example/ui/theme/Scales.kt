package com.example.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Шкала длительностей анимаций, мс. Компоненты берут длительности только отсюда или из
 * именованной константы своего файла (особая хореография, сверенная по эталону) — число
 * прямо в tween / durationMillis / delay запрещено тестом DesignSystemEnforcementTest.
 */
object ThingsMotion {
    /** Мгновенный отклик: смена цвета, проявление иконки */
    const val FAST = 100
    /** Короткий переход: подсветка, исчезновение элемента */
    const val QUICK = 150
    /** Базовый переход: фон строки, цвет, затемнение */
    const val BASE = 200
    /** Чуть длиннее базового: сдвиги и раскрытия небольших панелей */
    const val MEDIUM = 250
    /** Стандартное раскрытие и сворачивание (редактор задачи, переходы экранов) */
    const val STANDARD = 300
    /** Медленный переход: крупные перестроения */
    const val SLOW = 400
    /** Пауза перед уходом выполненной задачи и подобные выдержки */
    const val LONG = 500
}

/**
 * Шкала прозрачностей для `copy(alpha = …)`. Число прямо в `copy(alpha = …)` запрещено тестом;
 * особые значения — именованной константой в файле компонента.
 */
object ThingsAlpha {
    /** Едва заметная обводка и разделитель на тёмной подложке */
    const val FAINT = 0.08f
    /** Лёгкая подложка: выделение, подсветка */
    const val SUBTLE = 0.15f
    /** Слабый акцент: выделенная строка, неактивная иконка */
    const val LOW = 0.3f
    /** Приглушённое: служебные иконки в строке, недоступный пункт */
    const val MUTED = 0.4f
    /** Половина: плашка места вставки, вторичные элементы */
    const val HALF = 0.5f
    /** Подсказка в пустом поле и вспомогательный текст */
    const val HINT = 0.6f
}

/**
 * Шкала размеров иконок. Размер иконки — только отсюда или именованной константой файла
 * (особый размер, например значок в строке задачи 13 dp).
 */
object ThingsIconSize {
    val XS = 16.dp
    val S = 18.dp
    val M = 20.dp
    val L = 22.dp
    val XL = 24.dp
}

/**
 * Шкала отступов (сетка 4 dp). Общие отступы и промежутки — отсюда; геометрия конкретного
 * экрана (высота строки, поле списка) — в [AppDimens] (`MaterialTheme.dimens`).
 */
object ThingsSpacing {
    val NONE = 0.dp
    val XXS = 2.dp
    val XS = 4.dp
    /** Промежуточный шаг 6 dp: иконка → текст, малые вертикальные отступы */
    val XS_PLUS = 6.dp
    val S = 8.dp
    /** Промежуточный шаг 10 dp: поле строки, отступ под подзаголовком */
    val S_PLUS = 10.dp
    val M = 12.dp
    /** Промежуточный шаг 14 dp: поле списка и карточки */
    val M_PLUS = 14.dp
    val L = 16.dp
    /** Промежуточный шаг 20 dp: поле карточки, отступ над группой */
    val L_PLUS = 20.dp
    val XL = 24.dp
    val XXL = 32.dp
}

/** Тени: что оторвано от листа (см. «Формы и тени» в брендбуке) */
object ThingsElevation {
    val NONE = 0.dp
    /** Раскрытый редактор и перетаскиваемая карточка, строка или область */
    val CARD = 8.dp
    /** Кнопка «+» в покое */
    val FAB = 6.dp
    /** Кнопка «+», пока её тянут */
    val FAB_LIFTED = 18.dp
    /** Второй и третий слои стопки при групповом перетаскивании */
    val STACK_2 = 6.dp
    val STACK_3 = 4.dp
}

/** Толщины линий: разделители, обводки, штрихи */
object ThingsStroke {
    /** Разделитель на тёмной подложке, тонкая обводка карточки */
    val HAIRLINE = 0.5.dp
    /** Линия под подзаголовком и заголовком дня */
    val DIVIDER = 0.6.dp
    /** Обычная обводка и разделитель */
    val THIN = 1.dp
    /** Обводка выделенного (сегодняшний день в календаре) */
    val FOCUS = 1.5.dp
    /** Штрих индикатора и пунктира */
    val BOLD = 2.dp
}
